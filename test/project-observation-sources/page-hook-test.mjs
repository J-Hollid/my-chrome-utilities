import assert from "node:assert/strict";
import {observationArrayHook} from "../../dist/data-layer-installed/capture/observation-sources/page-hook.js";
const bus=new EventTarget();
globalThis.dispatchEvent=bus.dispatchEvent.bind(bus);
globalThis.dataLayer=[];globalThis.app={history:globalThis.dataLayer};
const received=[];
bus.addEventListener("marketing",e=>received.push(["marketing",e.detail]));
bus.addEventListener("app",e=>received.push(["app",e.detail]));
let calls=0;
const original=function(...items){calls++;assert.equal(this,globalThis.dataLayer);return Array.prototype.push.apply(this,items);};
dataLayer.push=original;
const attach=(path,channel,event)=>observationArrayHook("attach",path,channel,event);
const first=attach("dataLayer","m","marketing"),alias=attach("app.history","a","app");
assert.equal(first.status,"Ready");assert.equal(first.arrayId,alias.arrayId);
assert.equal(dataLayer.push({event:"A"},{event:"B"}),2);
assert.equal(calls,1);
assert.deepEqual(received.map(([s,e])=>[s,e.index,e.rawValue.event]),[["marketing",0,"A"],["app",0,"A"],["marketing",1,"B"],["app",1,"B"]]);
observationArrayHook("detach","dataLayer","m","");
dataLayer.push({event:"C"});
assert.equal(received.at(-1)[0],"app");
const resumed=attach("dataLayer","m","marketing");
assert.equal(resumed.arrayId,first.arrayId);assert.equal(resumed.rawValues.length,3);
const replacement=function(...items){return Array.prototype.push.apply(this,items);};
dataLayer.push=replacement;
observationArrayHook("detach","dataLayer","m","");
observationArrayHook("detach","app.history","a","");
assert.equal(dataLayer.push,replacement,"cleanup cannot restore a stale page function");
globalThis.dataLayer=[];
const changed=attach("dataLayer","m","marketing");
assert.notEqual(changed.arrayId,first.arrayId);
assert.equal(attach("unknown.queue","missing","none").status,"Waiting for path");
globalThis.scalar=17;
assert.equal(attach("scalar","scalar","none").status,"Not an array");
assert.equal(attach("__proto__.history","unsafe","none").status,"Waiting for path");
observationArrayHook("detach","dataLayer","m","");
console.log("Observation array hook tests passed");
