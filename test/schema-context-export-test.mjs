import assert from "node:assert/strict";
import Ajv2020 from "ajv/dist/2020.js";
import { createCanonicalSchema, applyCanonicalCommand } from "../dist/data-layer-canonical-schema.js";
import { createContextExportSnapshot, contextExportIdentity } from "../dist/schema-context-export/snapshot.js";

let sequence=0;
let canonical=createCanonicalSchema({id:"draft",contributorId:"purchase",contributorName:"Purchase"});
const add=(name,type,parentId)=>{
  const result=applyCanonicalCommand(canonical,{kind:"add",baseRevision:canonical.revision,name,type,parentId,id:()=>`property-${++sequence}`});
  assert.equal(result.status,"applied");canonical=result.document;
  return Object.values(canonical.nodes).find(node=>node.name===name).id;
};
const kind=add("kind","string"),amount=add("amount","number"),currency=add("currency","string");
const products=add("products","array");canonical.nodes[products].itemType="object";
const name=add("name","string",products);
const internalName=add("credentials","string");
canonical.onlyDefinedFields=true;
for(const id of [kind,amount,products,name])canonical.nodes[id].presence={mode:"required"};
canonical.nodes[currency].presence={mode:"required-when",condition:{kind:"predicate",propertyId:kind,operator:"Equals",value:"purchase"}};
canonical.nodes[currency].allowedValues=[{id:"eur",value:"EUR"},{id:"usd",value:"USD"}];
canonical.nodes[amount].rules=[{id:"minimum",kind:"range",minimum:10,maximum:1000,severity:"error"}];
canonical.nodes[amount].documentation={displayText:"",description:"Total",comments:"private",example:{method:"custom",value:12.5}};
canonical.nodes[products].concept="ecommerce";
const source=()=>({key:"checkout/cart/purchase",name:"Purchase",role:"Event occurrence",context:"Checkout · Cart",version:"Draft",canonical});
const before=JSON.stringify(canonical),snapshot=createContextExportSnapshot(source());
assert.equal(JSON.stringify(canonical),before,"export must not change the source");
assert.equal(snapshot.document.$schema,"https://json-schema.org/draft/2020-12/schema");
assert.equal(snapshot.document.$id,undefined);
assert.equal(snapshot.text,`${JSON.stringify(snapshot.document,null,2)}\n`);
assert.match(snapshot.filename,/purchase.*draft\.schema\.json$/);
assert.equal(snapshot.document.properties.products["x-concept"],"ecommerce");
assert.equal(snapshot.document.properties.products.items.properties.name["x-concept"],undefined);
assert.equal(snapshot.document.properties.credentials.type,"string");
assert.equal(snapshot.document.properties.amount.description,"Total");
assert.deepEqual(snapshot.document.properties.amount.examples,[12.5]);
const ajv=new Ajv2020({strict:false});
const validate=ajv.compile(snapshot.document);
const payload={kind:"purchase",amount:10,currency:"EUR",products:[{name:"Book"}]};
assert.equal(validate(payload),true);
for(const invalid of [{...payload,amount:9},{...payload,currency:undefined},{...payload,products:[{name:"Book"},{}]},{...payload,debug:true}])assert.equal(validate(invalid),false,JSON.stringify(invalid));
assert.equal(validate({...payload,kind:"view",currency:undefined}),true,"conditions must remain conditional");
const identity=contextExportIdentity(source());canonical.view="table";canonical.selectedPropertyId=internalName;
assert.equal(contextExportIdentity(source()),identity,"view state does not invalidate export");
canonical.nodes[amount].rules[0].minimum=20;
assert.notEqual(contextExportIdentity(source()),identity,"effective edits invalidate export");
assert.equal(validate(payload),true,"the snapshot stays frozen");
assert.throws(()=>createContextExportSnapshot({...source(),pending:true}),/save/i);
assert.throws(()=>createContextExportSnapshot({...source(),unconfirmed:true}),/confirm or cancel/i);
const invalid=structuredClone(canonical);delete invalid.nodes[products].itemType;
assert.throws(()=>createContextExportSnapshot({...source(),canonical:invalid}),/products.*item type/i);
const broken=structuredClone(canonical);broken.nodes[currency].presence.condition.propertyId="missing";
assert.throws(()=>createContextExportSnapshot({...source(),canonical:broken}),/reference/i);
canonical.nodes[amount].rules.push({id:"unknown",name:"Custom amount",kind:"custom",severity:"error"});
const lossy=createContextExportSnapshot(source());
assert.equal(lossy.compatibility.omitted.length,1);
assert.equal(lossy.compatibility.omitted[0].propertyPath,"/amount");
assert.equal(lossy.compatibility.omitted[0].ruleName,"Custom amount");
canonical.nodes[amount].rules.at(-1).condition={kind:"predicate",propertyId:"missing",operator:"Exists"};
assert.throws(()=>createContextExportSnapshot(source()),/reference/,"Lossy review cannot bypass a broken condition");
canonical.nodes[amount].rules.pop();canonical.nodes[amount].rules[0].minimum=2000;
assert.throws(()=>createContextExportSnapshot(source()),/conflicting numeric limits/);
console.log("Schema context snapshot: Draft, conditions, arrays, annotations, identity, blockers, and omissions passed.");
