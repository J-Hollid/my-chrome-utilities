(ns project-tools.crap
  (:require [clojure.java.io :as io]
            [clojure.string :as str]
            [crap4clj.core :as core]
            [crap4clj.coverage :as coverage]
            [crap4clj.crap :as crap]))

(def source-root "acceptance/src")
(def coverage-file "target/coverage/lcov.info")

(defn source-files []
  (->> (file-seq (io/file source-root))
       (filter #(and (.isFile %)
                     (re-find #"\.cljc?$" (.getName %))))
       (map #(.getPath %))
       sort))

(defn selected-sources [filters]
  (let [sources (source-files)]
    (if (seq filters)
      (filter #(some (fn [fragment] (str/includes? % fragment)) filters) sources)
      sources)))

(defn run-coverage! []
  (core/delete-coverage-dir "target/coverage")
  (core/run-coverage "clj -M:cov --lcov"))

(defn coverage-available? []
  (.isFile (io/file coverage-file)))

(defn report [filters]
  (let [lcov (coverage/load-lcov coverage-file)
        entries (mapcat #(core/analyze-file % lcov)
                        (selected-sources filters))]
    (crap/format-report (crap/sort-by-crap entries))))

(defn analyze! [filters]
  (let [status (run-coverage!)
        available? (coverage-available?)]
    (when-not (zero? status)
      (binding [*out* *err*]
        (println (str "Coverage failed (exit " status ")."))
        (println (if available?
                   "Reporting CRAP from the fresh LCOV generated by that complete test run."
                   "No fresh LCOV was generated; CRAP cannot be reported."))))
    {:status status
     :report (when available? (report filters))}))

(defn -main [& filters]
  (if (some #{"-h" "--help"} filters)
    (println "Usage: crap4clj [acceptance-source-path-fragment ...]")
    (let [{:keys [status report]} (analyze! filters)]
      (when report (println report))
      (when-not (zero? status) (System/exit status)))))
